export type TitleKey = keyof typeof TITLE_TRANSLATIONS;

const LEGACY_TITLE_KEYS: Record<string, TitleKey> = {
  'Line Lord': 'title_line_lord',
  'Zen Master': 'title_zen_master',
  'Combo King': 'title_combo_king',
  'Tetris Titan': 'title_tetris_titan',
  'Nint Legend': 'title_nint_legend'
};

function hasTitle(key: string): key is TitleKey {
  return Object.prototype.hasOwnProperty.call(TITLE_TRANSLATIONS, key);
}

export function getTitleLabel(value: string | null | undefined, language: Language): string {
  const raw = String(value || '').trim();
  if (!raw) return '';
  if (hasTitle(raw)) return TITLE_TRANSLATIONS[raw][language];
  const legacyKey = LEGACY_TITLE_KEYS[raw];
  return legacyKey ? TITLE_TRANSLATIONS[legacyKey][language] : raw;
}

export function getShopTitleLabel(itemId: string, value: string, language: Language): string {
  const translatedValue = getTitleLabel(value, language);
  if (translatedValue) return translatedValue;
  return hasTitle(itemId) ? TITLE_TRANSLATIONS[itemId][language] : '';
}
